# -----------------------------------------------------------------------------
# Montgomery-accelerated powMod (Zero-Copy Optimized)
# -----------------------------------------------------------------------------

template dhPowMod[B: static int](base, exponent, modulus: BigUint[B]): BigUint[B] =
  const W: int = B div 4

  let natBase: Nat[W] = bigUintToNat[B](base)
  let natMod: Nat[W] = bigUintToNat[B](modulus)

  let montCtx: MontgomeryCtx[W] = montgomery.initMontgomery(natMod)

  let expBytes: array[B, uint8] = fixedint.toBytesBE[B](exponent)

  let natResult: Nat[W] = montCtx.powMod(natBase, expBytes)
  nat32ToBigUint[B](natResult)

# -----------------------------------------------------------------------------
# Parameters
# -----------------------------------------------------------------------------

template two*[B: static int](): BigUint[B] =
  var res: BigUint[B]
  res[0] = 2.UINT
  res

template dhGenerateParameters*[B: static int](ctx: var DHCtx[B]) =
  when B == 256:
    ctx.parameters.p = fixedint.fromBytesBE[B](Modp2048P)
  elif B == 384:
    ctx.parameters.p = fixedint.fromBytesBE[B](Modp3072P)
  elif B == 512:
    ctx.parameters.p = fixedint.fromBytesBE[B](Modp4096P)
  else:
    {.error: "DH supports only 256, 384, and 512-byte groups".}

  var pMinusOne: BigUint[B] = subMod(ctx.parameters.p, one[B](), ctx.parameters.p)
  ctx.parameters.q = shiftRightOne(pMinusOne)
  ctx.parameters.g = two[B]()

template dhValidateParameters*[B: static int](parameters: DHParameters[B]): bool =
  let pNonZero = ctNonZero(parameters.p) == 1.UINT
  let gValid = ctEqual(parameters.g, two[B]())
  var expectedQ: BigUint[B] = shiftRightOne(subMod(parameters.p, one[B](), parameters.p))
  let qValid = ctEqual(parameters.q, expectedQ)

  pNonZero and gValid and qValid

# -----------------------------------------------------------------------------
# Key validation
# -----------------------------------------------------------------------------

template dhValidatePrivateKey*[B: static int](ctx: DHCtx[B]): bool =
  var vkValue: BigUint[B] = fixedint.fromBytesBE[B](ctx.privateKey.data)
  var vkTwo: BigUint[B] = addMod(one[B](), one[B](), ctx.parameters.p)
  var vkUpper: BigUint[B] = ctx.parameters.q
  not ctLess(vkValue, vkTwo) and ctLess(vkValue, vkUpper)

template dhValidatePublicKey*[B: static int](parameters: DHParameters[B], key: DHPublicKey[B]): bool =
  var vkValue: BigUint[B] = fixedint.fromBytesBE[B](key.data)
  var vkCheck: BigUint[B] = dhPowMod(vkValue, parameters.q, parameters.p)
  let oneVal = one[B]()
  var vkTwo: BigUint[B] = addMod(one[B](), one[B](), parameters.p)
  var vkUpper: BigUint[B] = subMod(parameters.p, vkTwo, parameters.p)

  not ctLess(vkValue, vkTwo) and ctLess(vkValue, vkUpper) and
    ctEqual(vkCheck, one[B]())

# -----------------------------------------------------------------------------
# Key generation
# -----------------------------------------------------------------------------

template dhGeneratePrivateKey*[B: static int](ctx: var DHCtx[B]) =
  if ctx.rng == nil: raise newException(PubKeyError, "nil RNG")

  let lowerBound = two[B]()
  let upperBound = ctx.parameters.q

  var candidate: BigUint[B]
  while true:
    ctx.rng(ctx.privateKey.data)
    candidate = fixedint.fromBytesBE[B](ctx.privateKey.data)
    if not ctLess(candidate, lowerBound) and ctLess(candidate, upperBound):
      break

template dhPublicKeyFromPrivate*[B: static int](ctx: var DHCtx[B]) =
  var pkPrivate: BigUint[B] = fixedint.fromBytesBE[B](ctx.privateKey.data)
  var pkPublic: BigUint[B] = dhPowMod(ctx.parameters.g, pkPrivate, ctx.parameters.p)
  ctx.publicKey.data = fixedint.toBytesBE[B](pkPublic)

# -----------------------------------------------------------------------------
# Core init / derive
# -----------------------------------------------------------------------------

template dhInitC*[B: static int](ctx: var DHCtx[B], random: Rng) =
  ctx.rng = random
  ctx.dhGenerateParameters()
  if not ctx.parameters.dhValidateParameters():
    raise newException(PubKeyError, "invalid DH parameters")
  ctx.dhGeneratePrivateKey()
  ctx.dhPublicKeyFromPrivate()
  if not ctx.parameters.dhValidatePublicKey(ctx.publicKey):
    raise newException(PubKeyError, "invalid DH public key")

template dhDeriveC*[B: static int](ctx: DHCtx[B], peer: DHPublicKey[B]): DHSharedSecret[B] =
  if not ctx.dhValidatePrivateKey() or
     not ctx.parameters.dhValidatePublicKey(peer):
    raise newException(PubKeyError, "invalid DH key")

  var drPrivate: BigUint[B] = fixedint.fromBytesBE[B](ctx.privateKey.data)
  var drPeer: BigUint[B] = fixedint.fromBytesBE[B](peer.data)
  var drSecret: BigUint[B] = dhPowMod(drPeer, drPrivate, ctx.parameters.p)
  var drOutput: DHSharedSecret[B] = fixedint.toBytesBE[B](drSecret)

  var drZero: UINT = 0.UINT
  for drI in 0 ..< B:
    drZero = drZero or UINT(drOutput[drI])
  if drZero == 0.UINT:
    raise newException(PubKeyError, "invalid DH shared secret")

  drOutput

