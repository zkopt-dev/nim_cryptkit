template kupynaGCore[N: static int](x: array[N, uint64], j: int): uint64 =
  const lastShift: int = (N div 2) - 3
  var output: uint64 = Table[0][int(uint8(x[j]))]
  output = output xor Table[1][int((x[(j - 1 + N) mod N] shr  8) and 0xFF'u8)]
  output = output xor Table[2][int((x[(j - 2 + N) mod N] shr 16) and 0xFF'u8)]
  output = output xor Table[3][int((x[(j - 3 + N) mod N] shr 24) and 0xFF'u8)]
  output = output xor Table[4][int((x[(j - 4 + N) mod N] shr 32) and 0xFF'u8)]
  output = output xor Table[5][int((x[(j - 5 + N) mod N] shr 40) and 0xFF'u8)]
  output = output xor Table[6][int((x[(j - 6 + N) mod N] shr 48) and 0xFF'u8)]
  output = output xor Table[7][int((x[(j + lastShift) mod N] shr 56) and 0xFF'u8)]

  output

template kupynaG[N: static int](x: array[N, uint64], mode: static int, round: uint64): array[N, uint64] =
  var output: array[N, uint64]
  for j in static(0 ..< N):
    output[j] = kupynaGCore(x, j)
    when mode == 0:
      discard
    elif mode == 1:
      output[j] = output[j] xor ((uint64(j) shl 4) xor round.uint64)
    else:
      const RC: uint64 = 0x00F0F0F0F0F0F0F3'u64
      output[j] = output[j] + (RC xor ((((uint64(N - 1 - j) * 0x10'u64) xor round.uint64) shl 56)))

  output

template kupynaP[N: static int](x: var array[N, uint64], round: int): void =
  for i in static(0 ..< N):
    x[i] = x[i] xor ((uint64(i) shl 4) xor round.uint64)
  var y = kupynaG(x, 1, round.uint64 + 1'u64)
  x = kupynaG(y, 0, 0'u64)

template kupynaQ[N: static int](x: var array[N, uint64], round: int): void =
  const RC: uint64 = 0x00F0F0F0F0F0F0F3'u64
  for j in static(0 ..< N):
    x[j] = x[j] + (RC xor ((((uint64(N - 1 - j) * 0x10'u64) xor round.uint64) shl 56)))
  var y = kupynaG(x, 2, round.uint64 + 1'u64)
  x = kupynaG(y, 0, 0'u64)

template kupynaTransform[N, B: static int](state: var array[N, uint64], chunk: slicearray[B, uint8]): void =
  when LE:
    var message: ptr array[N, uint64] = cast[ptr array[N, uint64]](addr chunk[0])
  else:
    var message: array[N, uint64]
    decodeLE(chunk, message.toSliceArray(0, N - 1))

  var aq, ap: array[N, uint64]
  for i in static(0 ..< N):
    ap[i] = state[i] xor message[i]
    aq[i] = message[i]

  const rounds: int = when N == 8: 10 else: 14

  for i in static(0 ..< (rounds div 2)):
    kupynaP(ap, i * 2)
    kupynaQ(aq, i * 2)

  for i in static(0 ..< N):
    state[i] = state[i] xor ap[i] xor aq[i]

template kupynaFinalTransform[N: static int](state: var array[N, uint64]): void =
  var temp: array[N, uint64] = state
  const rounds: int = when N == 8: 10 else: 14

  for i in static(0 ..< rounds div 2):
    kupynaP(temp, i * 2)

  for i in static(0 ..< N):
    state[i] = state[i] xor temp[i]

template kupynaInitC[K, B: static int](ctx: var KupynaCtx[K, B]): void =
  when B == 64:
    zeroMem(addr ctx.state, 64)
  else:
    zeroMem(addr ctx.state, 128)
  zeroMem(addr ctx.buffer, B)
  ctx.index = 0
  ctx.length = 0'u64
  ctx.state[0] = uint64(B)

template kupynaInputC[K, B: static int](ctx: var KupynaCtx[K, B], input: openArray[uint8]): void =
  let inputLen: int = input.len
  var check: bool = true

  if inputLen <= 0: check = false

  if check:
    var index: int = ctx.index
    ctx.length += uint64(inputLen)

    let left: int = B - index
    var position: int = 0

    if inputLen >= left:
      if left > 0:
        copyMem(addr ctx.buffer[index], addr input[0], left)
      kupynaTransform(ctx.state, ctx.buffer.toSliceArray(0, B - 1))
      position = left
      index = 0

      while position + 64 <= inputLen:
        kupynaTransform(ctx.state, input.toSliceArray(position, position + B - 1, B))
        position += B

    let remain: int = inputLen - position
    if remain > 0:
      copyMem(addr ctx.buffer[index], addr input[position], remain)
      index += remain

    ctx.index = index

template kupynaFinalC[K, B: static int](ctx: var KupynaCtx[K, B]): array[K, uint8] =
  var output: array[K, uint8]
  var index: int = ctx.index

  ctx.buffer[index] = 0x80'u8
  index.inc

  let padLen: int = if index <= B - 12: B - 12 - index else: B - index

  if index <= B - 12:
    zeroMem(addr ctx.buffer[index], padLen)
  else:
    if padLen > 0:
      zeroMem(addr ctx.buffer[index], padLen)
    kupynaTransform(ctx.state, ctx.buffer.toSliceArray(0, B - 1))
    zeroMem(addr ctx.buffer[0], B - 12)

  ctx.length = ctx.length shl 3
  toBytesLE(ctx.length, ctx.buffer.toSliceArray(B - 12, B - 5))

  zeroMem(addr ctx.buffer[B - 4], 4)

  kupynaTransform(ctx.state, ctx.buffer.toSliceArray(0, B - 1))

  kupynaFinalTransform(ctx.state)

  var temp: array[B, uint8]
  encodeLE(ctx.state, temp)

  const starts: int = B - K
  copyMem(addr output[0], addr temp[starts], K)

  output
