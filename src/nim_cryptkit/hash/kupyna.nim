proc kupynaAppendLe64(data: var seq[uint8], value: uint64) =
  for i in 0 ..< 8:
    data.add(uint8((value shr (i * 8)) and 0xff'u64))

proc kupynaAppendKeyPad(data: var seq[uint8], keyLen: static int) =
  when keyLen == 32:
    for i in 0 ..< 32:
      if i == 0:
        data.add(0x80'u8)
      elif i == 21:
        data.add(0x01'u8)
      else:
        data.add(0'u8)
  elif keyLen == 48:
    for i in 0 ..< 80:
      if i == 0 or i == 68:
        data.add(0x80'u8)
      elif i == 69:
        data.add(0x01'u8)
      else:
        data.add(0'u8)
  elif keyLen == 64:
    for i in 0 ..< 64:
      if i == 0:
        data.add(0x80'u8)
      elif i == 53:
        data.add(0x02'u8)
      else:
        data.add(0'u8)
  else:
    {.fatal: "unsupported Kupyna KMAC key size".}

proc kupynaKmacImpl[K, B, KeyLen: static int](key, input: openArray[uint8]): array[
    K, uint8] =
  doAssert key.len == KeyLen
  var data = newSeq[uint8]()
  for b in key:
    data.add(b)
  kupynaAppendKeyPad(data, KeyLen)
  for b in input:
    data.add(b)

  let n = uint64(input.len)
  let padSize =
    when K == 32:
      if n < 52'u64: 51'u64 - n else: 63'u64 - ((n - 52'u64) mod 64'u64)
    else:
      if n < 116'u64: 115'u64 - n else: 127'u64 - ((n - 116'u64) mod 128'u64)

  data.add(0x80'u8)
  for _ in 0 ..< int(padSize):
    data.add(0'u8)
  kupynaAppendLe64(data, n * 8'u64)
  for _ in 0 ..< 4:
    data.add(0'u8)
  for i in 0 ..< KeyLen:
    data.add(not key[i])

  result = kupynaDigestImpl[K, B](data)

proc kupynaKmacAnyImpl(key, input: openArray[uint8]): seq[uint8] =
  case key.len
  of 32:
    let digest = kupynaKmacImpl[32, 64, 32](key, input)
    result = @digest
  of 48:
    let digest = kupynaKmacImpl[48, 128, 48](key, input)
    result = @digest
  of 64:
    let digest = kupynaKmacImpl[64, 128, 64](key, input)
    result = @digest
  else:
    result = @[]
