template groestlInitC[K, B: static int](ctx: var GroestlCtx[K, B]): void =
  zeroMem(addr ctx.state, sizeof(ctx.state))
  zeroMem(addr ctx.buffer, B)
  ctx.index = 0
  ctx.length = 0'u64
  when B == 64:
    ctx.state[7] = swap(uint64(K * 8))
  else:
    ctx.state[15] = swap(uint64(K * 8))

template groestlInputC[K, B: static int](ctx: var GroestlCtx[K, B], input: openArray[uint8]): void =
  var inputLen: int = input.len
  var check: bool = true

  if inputLen <= 0: check = false

  if check:
    var index: int = ctx.index
    ctx.length += inputLen.uint64

    let left: int = B - index
    var position: int = 0

    if inputLen >= left:
      if left > 0:
        copyMem(addr ctx.buffer[index], addr input[0], left)
      when B == 64:
        groestl256Transform(ctx.state, ctx.buffer.toSliceArray(0, 63))
      elif B == 128:
        groestl512Transform(ctx.state, ctx.buffer.toSliceArray(0, 127))
      position = left
      index = 0

      while position + B <= inputLen:
        when B == 64:
          groestl256Transform(ctx.state, input.toSliceArray(position, position + 63, 64))
        elif B == 128:
          groestl512Transform(ctx.state, input.toSliceArray(position, position + 127, 128))
        position += B

    let remain: int = inputLen - position
    if remain > 0:
      copyMem(addr ctx.buffer[index], addr input[position], remain)
      index += remain

    ctx.index = index

template groestlFinalC[K, B: static int](ctx: var GroestlCtx[K, B]): array[K, uint8] =
  var output: array[K, uint8]

  var index: int = ctx.index

  ctx.buffer[index] = 0x80'u8
  index.inc

  ctx.length += 1'u64

  let padLen: int = if index <= B - 8: B - 8 - index else: B - index

  if index <= B - 8:
    zeroMem(addr ctx.buffer[index], padLen)
  else:
    if padLen > 0:
      zeroMem(addr ctx.buffer[index], padLen)
    when B == 64:
      groestl256Transform(ctx.state, ctx.buffer.toSliceArray(0, 63))
    else:
      groestl512Transform(ctx.state, ctx.buffer.toSliceArray(0, 127))
    ctx.length += uint64(B - index)
    index = 0
    zeroMem(addr ctx.buffer[0], B - 8)

  ctx.length += uint64(B - index)
  let count: uint64 = swap(ctx.length div uint64(B))
  toBytesLE(count, ctx.buffer.toSliceArray(B - 8, B - 1))

  when B == 64:
    groestl256Transform(ctx.state, ctx.buffer.toSliceArray(0, 63))
    groestl256FinalTransform(ctx.state)
    var temp: array[64, uint8]
    encodeLE(ctx.state, temp)
  else:
    groestl512Transform(ctx.state, ctx.buffer.toSliceArray(0, 127))
    groestl512FinalTransform(ctx.state)
    var temp: array[128, uint8]
    encodeLE(ctx.state, temp)

  const starts: int = B - K
  copyMem(addr output, addr temp[starts], K)
  output
