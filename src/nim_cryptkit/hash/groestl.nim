proc roundP256(x: var array[8, uint64], y: var array[8, uint64], r: uint64) =
  for i in static(0 ..< 8):
    x[i] = x[i] xor ((uint64(i) shl 4) xor r)
  for c in static(0 ..< 8):
    y[c] = Table[0][int((x[(c + 0) mod 8]       ) and 0xFF'u8)] xor
           Table[1][int((x[(c + 1) mod 8] shr  8) and 0xFF'u8)] xor
           Table[2][int((x[(c + 2) mod 8] shr 16) and 0xFF'u8)] xor
           Table[3][int((x[(c + 3) mod 8] shr 24) and 0xFF'u8)] xor
           Table[4][int((x[(c + 4) mod 8] shr 32) and 0xFF'u8)] xor
