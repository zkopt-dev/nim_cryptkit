template groestl256Transform(state: var array[8, uint64], chunk: slicearray[64, uint8]): void =
  var words: array[8, uint64]
  decodeLE(chunk, words.toSliceArray(0, 7))

  var aq1, aq2, ap1, ap2: array[8, uint64]
  for column in static(0 ..< 8):
    ap1[column] = state[column] xor words[column]
    aq1[column] = words[column]

  for i in static(0 ..< 5):
    roundP256(ap1, ap2, uint64(i * 2 + 0))
    roundP256(ap2, ap1, uint64(i * 2 + 1))
    roundQ256(aq1, aq2, uint64(i * 2 + 0) shl 56)
    roundQ256(aq2, aq1, uint64(i * 2 + 1) shl 56)

  for column in static(0 ..< 8):
    state[column] = ap1[column] xor aq1[column] xor state[column]

template groestl512Transform(state: var array[16, uint64], chunk: slicearray[128, uint8]): void =
  var words: array[16, uint64]
  decodeLE(chunk, words.toSliceArray(0, 15))

  var aq1, aq2, ap1, ap2: array[16, uint64]

  for column in static(0 ..< 16):
