# ============================================================
# AES-CCM official test vectors
#   * RFC 3610 "Counter with CBC-MAC (CCM)" Packet Vectors #1-#24.
#     Each packet has an 8- or 12-byte cleartext header (the
#     associated data) followed by the payload.  The published
#     output is AAD || ciphertext || tag.
# ============================================================

var passed = 0

template ccmVector(C, init, encrypt: untyped, T: static int,
                   name, keyHex, nonceHex, aadHex, ptHex, ctHex, tagHex: string) =
  let key = hexToBin(keyHex).value
  let nonce = hexToBin(nonceHex).value
  let aad = hexToBin(aadHex).value
  let pt = hexToBin(ptHex).value

  let (ct, tag) = ccmEncryptOne[C, 16, 16, T](init, encrypt, key, nonce, aad, pt)
  doAssert sameHex(binToHex(ct), ctHex),
    name & " ciphertext mismatch: got " & binToHex(ct) & " want " & ctHex
  doAssert sameHex(binToHex(tag), tagHex),
    name & " tag mismatch: got " & binToHex(tag) & " want " & tagHex

  let ctBytes = hexBytes(ctHex)
  let tagBytes = hexBytes(tagHex)
  let res = ccmDecryptOne[C, 16, 16, T](init, encrypt, key, nonce, aad, ctBytes, tagBytes)
  doAssert res.kind == Success, name & " decrypt failed"
  doAssert sameHex(binToHex(res.value), ptHex),
    name & " decrypt mismatch: got " & binToHex(res.value) & " want " & ptHex

  # A forged tag must be rejected.
  var badTag = tagBytes
  badTag[0] = badTag[0] xor 0x01
  let bad = ccmDecryptOne[C, 16, 16, T](init, encrypt, key, nonce, aad, ctBytes, badTag)
  doAssert bad.kind == Failure, name & " accepted a forged tag"

  inc passed

